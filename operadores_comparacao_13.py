#       2. Operadores
#
#               ">" -> Maior que 
#                   - Ex:.
#                       100 > 10 
#                           - True
#
#               "<" -> Menor que
#                   - Ex:.
#                       100 < 10
#                           - False
#
#               ">=" -> Maior ou igual a 
#                   - Ex:.
#                       100 >= (10 ** 2)
#                           - True
#
#               "<=" -> Menor ou igual a
#                   - Ex:.
#                       7/2 <= (1.8 * 2)
#                           - True
#
#               "==" -> É semelhante/igual
#                   - Ex:. 
#                       10 == 10 
#                           - True
#
#               "!=" -> É diferente de
#                   - Ex:.
#                       18/9 != 2
#                           - False
#
#       3. Observação
#               "=" é diferente de "=="
#
#               a. =
#                   - Atribuir valor a uma variável 
#
#               b. ==
#                   - Comparar valor entre duas variáveis
