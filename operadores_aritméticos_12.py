# Operadores Aritméticos
#       - Fazer cálculos
#       
#       1. Operadores (Explicação)
#               - Operadores = Símbolos
#               - Estrutura
#                       - x / y 
#                           - x e y -> Operandos
#                           - / -> Operador 
#
#                       - Operador + Operandos = Expressão
#                               x / y -> Expressão
#
#       2. Operadores (Exemplos)
#               ** -> Expoente
#                   - Ex:.
#                       7 ** 2 = 49
#
#               % -> Módulo ou Resto 
#                   - Ex:.
#                       7 % 2 = 1
#
#               // -> Divisão (resultado inteiro)
#                   - Ex:. 
#                       7 // 2 = 3 (resultado somente em inteiro)
#
#               / -> Divisão
#                   - Ex:.
#                       7 / 2 = 3.5 
#
#               * -> Multiplicação
#                   - Ex:. 
#                       7 * 2 = 14
#
#               - -> Substração
#                   - Ex:. 
#                       7 - 2 = 5 
#
#               + -> Adição
#                   - Ex:.
#                       7 + 2 = 9 
#
#       3. Ordem das Operações
#           - Nível de Prioridade
#                   - Parênteses
#                   - Exponenciação
#                   - Multiplicação, divisão, resto
#                   - Adição e Subtração
#
#           - Ex:.
#                   calculo_1 = (2 + 5) / 2
#                   print (resultado) // 3.5      -> Parênteses (Prioridade)
#
#                   calculo_2 = 2 + 5 / 2
#                   print (resultado) // 4.5      -> Divisão (Prioridade)
#
#                   calculo_3 = 2 + 5 - 1
#                   print (resultado) // 6        -> + e - (Mesmo nível de prioridade) -> Começar pela esquerda
#
